"""Chunked source profiling. Reports source shape, nulls, dtypes, key duplicates and date parse issues."""
import argparse, json
from collections import Counter
from pathlib import Path
import pandas as pd
from config.settings import ROOT, RAW, PROFILE

SPECS = {
    "m5/calendar.csv": ("m5/calendar.csv", "utf-8", ["d"], ["date"]),
    "m5/sales_train_validation.csv": ("m5/sales_train_validation.csv", "utf-8", ["id"], []),
    "m5/sales_train_evaluation.csv": ("m5/sales_train_evaluation.csv", "utf-8", ["id"], []),
    "m5/sell_prices.csv": ("m5/sell_prices.csv", "utf-8", ["store_id", "item_id", "wm_yr_wk"], []),
    "olist/orders": ("olist/olist_orders_dataset.csv", "utf-8", ["order_id"], ["order_purchase_timestamp", "order_approved_at", "order_delivered_carrier_date", "order_delivered_customer_date", "order_estimated_delivery_date"]),
    "olist/order_items": ("olist/olist_order_items_dataset.csv", "utf-8", ["order_id", "order_item_id"], ["shipping_limit_date"]),
    "olist/products": ("olist/olist_products_dataset.csv", "utf-8", ["product_id"], []),
    "olist/sellers": ("olist/olist_sellers_dataset.csv", "utf-8", ["seller_id"], []),
    "olist/customers": ("olist/olist_customers_dataset.csv", "utf-8", ["customer_id"], []),
    "olist/payments": ("olist/olist_order_payments_dataset.csv", "utf-8", ["order_id", "payment_sequential"], []),
    "scms/delivery_history": ("scms/SCMS_Delivery_History_Dataset_20150929.csv", "latin1", ["ID"], ["PQ First Sent to Client Date", "PO Sent to Vendor Date", "Scheduled Delivery Date", "Delivered to Client Date", "Delivery Recorded Date"]),
}


def profile_one(rel, encoding, key_cols, date_cols, chunksize):
    path = RAW / rel
    if not path.exists():
        return {"file": str(path), "status": "MISSING"}
    header = pd.read_csv(path, nrows=0, encoding=encoding).columns.tolist()
    rows, nulls, dupes, date_invalid = 0, Counter(), 0, Counter()
    dtypes = {}
    for chunk in pd.read_csv(path, chunksize=chunksize, encoding=encoding, low_memory=False):
        rows += len(chunk)
        nulls.update(chunk.isna().sum().to_dict())
        if not dtypes:
            dtypes = {k: str(v) for k, v in chunk.dtypes.items()}
        valid_keys = [c for c in key_cols if c in chunk.columns]
        if valid_keys:
            dupes += int(chunk.duplicated(subset=valid_keys).sum())
        for col in date_cols:
            if col in chunk.columns:
                raw = chunk[col]
                parsed = pd.to_datetime(raw, errors="coerce", dayfirst=False)
                date_invalid[col] += int((raw.notna() & parsed.isna()).sum())
    return {
        "file": str(path.relative_to(ROOT.parent)), "status": "PROFILED", "rows": rows,
        "columns": len(header), "headers": header, "dtypes_first_chunk": dtypes,
        "missing_values_by_column": dict(nulls),
        "duplicate_keys_within_chunks": dupes,
        "duplicate_check_note": "Duplicates are counted within each chunk; cross-chunk duplicates are not included in this profiling pass.",
        "candidate_key": key_cols, "invalid_non_null_dates_by_column": dict(date_invalid),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--chunksize", type=int, default=200_000)
    args = parser.parse_args()
    result = {name: profile_one(*spec, args.chunksize) for name, spec in SPECS.items()}
    PROFILE.parent.mkdir(parents=True, exist_ok=True)
    PROFILE.write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")
    lines = ["# Source profiling report", "", "Generated by `profiling/profile_sources.py`.", "",
             "Duplicate counts below are chunk-local, not a complete cross-chunk uniqueness proof.", "",
             "| Source file | Rows | Columns | Candidate key | Missing values |", "|---|---:|---:|---|---:|"]
    for name, r in result.items():
        if r.get("status") != "PROFILED":
            lines.append(f"| {name} | MISSING | | | |")
        else:
            missing = sum(r["missing_values_by_column"].values())
            lines.append(f"| {name} | {r['rows']:,} | {r['columns']} | `{', '.join(r['candidate_key'])}` | {missing:,} |")
    (ROOT / "profiling" / "source_profile.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {PROFILE} and source_profile.md")

if __name__ == "__main__":
    main()
